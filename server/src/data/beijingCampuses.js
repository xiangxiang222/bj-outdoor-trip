function packColleges(names) {
  return names.map((n) => ({ name: n, majors: [] }));
}

function school(name, aliases, kind, colleges) {
  const set = colleges || COLLEGE_SETS[kind] || COMPREHENSIVE;
  return {
    name,
    aliases: aliases || [],
    kind: kind || "comprehensive",
    colleges: packColleges(set),
  };
}

